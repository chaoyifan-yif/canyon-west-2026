const {chromium}=require('C:/Users/56348/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8787/#daily/3');
  await page.waitForSelector('.meal-panel');
  assert.equal(await page.locator('.meal-panel').count(),3);
  assert.equal(await page.locator('.meal-panel').first().locator('.meal-option').count(),3);
  assert.ok(await page.locator('.star-panel').count());
  await page.locator('[data-pick-meal="d3-12"][data-candidate="1"]').click();
  assert.match(await page.locator('[data-meal-form="d3-12"] input[name="name"]').inputValue(),/BirdHouse/);
  await page.locator('[data-meal-form="d3-12"] input[name="spent"]').fill('38.50');
  await page.locator('[data-meal-form="d3-12"] select[name="rating"]').selectOption('5');
  await page.locator('[data-meal-form="d3-12"] textarea[name="note"]').fill('鸡肉很好吃');
  await page.locator('[data-meal-form="d3-12"] button[type="submit"]').click();
  await page.locator('[data-star-status="3"]').selectOption('go');
  await page.goto('http://127.0.0.1:8787/#ledger');
  await page.waitForSelector('.ledger-summary');
  assert.match(await page.locator('.ledger-summary').innerText(),/38\.50/);
  assert.match(await page.locator('.expense-row').innerText(),/BirdHouse/);
  await page.locator('#expense-form input[name="title"]').fill('加油站');
  await page.locator('#expense-form input[name="amount"]').fill('41.25');
  await page.locator('#expense-form select[name="category"]').selectOption('fuel');
  await page.locator('#expense-form button[type="submit"]').click();
  assert.equal(await page.locator('.expense-row').count(),2);
  await page.reload();
  assert.equal(await page.locator('.expense-row').count(),2);
  await page.locator('#ledger-category').selectOption('fuel');
  assert.equal(await page.locator('.expense-row').count(),1);
  await page.locator('.expense-row [data-edit-expense]').click();
  assert.equal(await page.locator('#expense-form input[name="amount"]').inputValue(),'41.25');
  await page.locator('#expense-form input[name="amount"]').fill('42.00');
  await page.locator('#expense-form button[type="submit"]').click();
  assert.match(await page.locator('.expense-row').innerText(),/42\.00/);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  fs.mkdirSync('qa',{recursive:true});
  await page.screenshot({path:'qa/mobile-ledger.png',fullPage:true});
  await page.goto('http://127.0.0.1:8787/#daily/4');
  assert.ok(await page.locator('.star-panel').count());
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'qa/mobile-star.png',fullPage:true});
  await page.goto('http://127.0.0.1:8787/#daily/3');
  await page.locator('[data-meal-form="d3-12"]').scrollIntoViewIfNeeded();
  await page.screenshot({path:'qa/mobile-meal.png'});
  assert.deepEqual(errors,[]);
  console.log('feature QA passed: meal selection, review, expense, edit, persistence, star panels, mobile overflow');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
